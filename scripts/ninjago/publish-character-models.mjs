#!/usr/bin/env node
/**
 * Publish the original fighter models produced by LEGO-Ninjago-Tournament.
 * Run after checking out the pinned game source and running its asset generator.
 * These are hand-authored/procedural meshes, NOT outputs from TRELLIS.2 inference.
 */
import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';

const GAME_SOURCE = resolve(process.argv[2] || 'source-game');
const OUTPUT = resolve('assets/ninjago/characters');
const REMASTER_IDS = [
  'kai-tournament',
  'jay-tournament',
  'cole-tournament',
  'zane-techno',
  'zane-zx',
  'nya',
  'skylor',
  'master-chen',
  'master-garmadon'
];
const SOURCES = [
  ...REMASTER_IDS.map(id => ({
    id,
    path: `public/assets/models/fighters/variants/${id}/cartoon-remaster.glb`,
    type: 'original-procedural-remaster'
  })),
  {
    id: 'lloyd-tournament',
    path: 'public/assets/models/fighters/variants/lloyd-tournament/lloyd-exact.glb',
    type: 'original-authored-mould-model'
  }
];

function inspectGlb(data, id) {
  if (data.length < 28 ||
      data.readUInt32LE(0) !== 0x46546c67 ||
      data.readUInt32LE(4) !== 2 ||
      data.readUInt32LE(8) !== data.length ||
      data.readUInt32LE(16) !== 0x4e4f534a) {
    throw new Error(`${id}: invalid glTF 2.0 binary header`);
  }
  const jsonLength = data.readUInt32LE(12);
  if (jsonLength > data.length - 20) throw new Error(`${id}: invalid JSON chunk length`);
  const json = JSON.parse(data.subarray(20, 20 + jsonLength).toString('utf8').trim());
  if (json.asset?.version !== '2.0' || !Array.isArray(json.meshes) || json.meshes.length === 0) {
    throw new Error(`${id}: missing glTF meshes`);
  }
  const nodes = new Set((json.nodes ?? []).map(node => node.name));
  for (const part of ['torso', 'head', 'leftArm', 'rightArm', 'leftLeg', 'rightLeg']) {
    if (!nodes.has(part)) throw new Error(`${id}: required animation part ${part} missing`);
  }
  return { meshes: json.meshes.length, nodes: json.nodes.length };
}

async function main() {
  const entries = [];
  for (const source of SOURCES) {
    const sourcePath = resolve(GAME_SOURCE, source.path);
    const data = await readFile(sourcePath);
    const parts = inspectGlb(data, source.id);
    const outputPath = resolve(OUTPUT, `${source.id}.glb`);
    await mkdir(dirname(outputPath), { recursive: true });
    await copyFile(sourcePath, outputPath);
    entries.push({
      id: source.id,
      file: `${source.id}.glb`,
      source: source.path,
      format: 'glTF 2.0 / binary GLB',
      type: source.type,
      bytes: data.length,
      sha256: createHash('sha256').update(data).digest('hex'),
      ...parts
    });
    console.log(`${source.id}: ${data.length.toLocaleString()} bytes, ${parts.meshes} meshes, ${parts.nodes} nodes`);
  }
  const manifest = {
    schemaVersion: 1,
    title: 'Ninjago Tournament Character Assets',
    provenance: 'Original authored/procedural game models; not generated by TRELLIS.2.',
    gameRepository: 'https://github.com/yousseffekryk98-droid/LEGO-Ninjago-Tournament',
    characters: entries
  };
  await writeFile(resolve(OUTPUT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  console.log(`Published ${entries.length} character GLBs to assets/ninjago/characters/`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
